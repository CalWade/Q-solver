import { test, expect } from '@playwright/test'

async function rpc(request, method, ...args) {
  const response = await request.post(`/rpc/${method}`, { data: args })
  expect(response.ok(), await response.text()).toBeTruthy()
  return response.json()
}
async function send(request) {
  await rpc(request, 'TriggerSend')
  const state = await rpc(request, 'GetWorkflowStatus')
  await expect.poll(async () => (await rpc(request, 'HarnessModelSnapshot')).some(call => call.id === state.requestId)).toBe(true)
  return state.requestId
}
test.beforeEach(async ({ page, request }) => {
  await rpc(request, 'HarnessReset')
  const cfg = await rpc(request, 'GetSettings')
  Object.assign(cfg, { apiKey: 'synthetic-test-key', model: 'fixture-a', keepContext: true })
  expect(await rpc(request, 'UpdateSettings', JSON.stringify(cfg))).toBe('')
  await page.goto('/')
  await expect(page.getByTitle('设置', { exact: true })).toBeVisible()
})

test('native command adapter → screenshot queue → request snapshot → primary UI and SSE final answer', async ({ page, request, context }) => {
  const viewer = await context.newPage()
  // Exercise the viewer's offline fallback; test never depends on CDN resources.
  await viewer.route(/^https?:\/\/(?!127\.0\.0\.1)/, route => route.abort())
  await viewer.goto('/broadcast/')
  await expect(viewer.locator('#status-text')).toHaveText('已连接')
  const cfg = await rpc(request, 'GetSettings')
  cfg.shortcuts.screenshot = { keys: ['Control', 'KeyQ'] }
  expect(await rpc(request, 'UpdateSettings', JSON.stringify(cfg))).toBe('')
  await rpc(request, 'HarnessInput', [{ key: 'ControlLeft', down: true }, { key: 'KeyQ', down: true }, { key: 'KeyQ', down: false }, { key: 'ControlLeft', down: false }])
  await expect(page.locator('.dock-count')).toHaveText('1/3')
  await rpc(request, 'TriggerScreenshot')
  await expect(page.locator('.dock-count')).toHaveText('2/3')
  const id = await send(request)
  await expect(page.locator('.screenshot-dock')).toBeHidden()
  await expect(page.getByTestId('cancel-request')).toBeVisible()
  cfg.model = 'fixture-b'
  expect(await rpc(request, 'UpdateSettings', JSON.stringify(cfg))).toBe('')
  const call = (await rpc(request, 'HarnessModelSnapshot')).find(call => call.id === id)
  expect(call).toMatchObject({ model: 'fixture-a', images: 2, history: 0 })
  await rpc(request, 'HarnessModelChunk', id, '推导过程', true)
  await rpc(request, 'HarnessModelChunk', id, '草稿答案')
  await expect(page.locator('.ai-response').last()).toContainText('草稿答案')
  await expect(viewer.locator('#content')).toHaveText('草稿答案')
  await rpc(request, 'HarnessModelFinish', id, '最终核对后的答案')
  await expect(page.locator('.ai-response').last()).toHaveText('最终核对后的答案')
  await expect(viewer.locator('#content')).toHaveText('最终核对后的答案')
  await expect(page.getByTestId('cancel-request')).toBeHidden()
  await viewer.reload()
  await expect(viewer.locator('#status-text')).toHaveText('已完成')
  await expect(viewer.locator('#content')).toHaveText('最终核对后的答案')
  const next = await send(request)
  expect((await rpc(request, 'HarnessModelSnapshot')).find(call => call.id === next)).toMatchObject({ model: 'fixture-b', history: 1 })
  await rpc(request, 'HarnessModelFinish', next, '第二轮')
  await expect(page.locator('.ai-response')).toHaveCount(2)
  await viewer.close()
})

test('cancel preserves partial content and late callbacks cannot change the next request', async ({ page, request, context }) => {
  const viewer = await context.newPage()
  await viewer.route(/^https?:\/\/(?!127\.0\.0\.1)/, route => route.abort())
  await viewer.goto('/broadcast/')
  const first = await send(request)
  await rpc(request, 'HarnessModelChunk', first, '已收到的部分')
  await expect(page.locator('.ai-response').last()).toContainText('已收到的部分')
  await page.getByTestId('cancel-request').click()
  await expect(page.getByTestId('cancel-request')).toBeHidden()
  await expect(viewer.locator('#status-text')).toHaveText('已停止')
  await expect(page.locator('.ai-response').last()).toHaveText('已收到的部分')
  const second = await send(request)
  expect(await rpc(request, 'CancelRequest', first)).toBe(false)
  await rpc(request, 'HarnessModelChunk', first, '不应该出现的旧内容')
  await rpc(request, 'HarnessModelChunk', second, '新的答案')
  await rpc(request, 'HarnessModelFinish', first, '不应该出现的旧结果')
  await rpc(request, 'HarnessModelFinish', second, '新的最终答案')
  await expect(page.locator('.ai-response').last()).toHaveText('新的最终答案')
  await expect(viewer.locator('#content')).toHaveText('新的最终答案')
  await expect(page.locator('body')).not.toContainText('不应该出现')
  await viewer.close()
})

test('reloading during generation restores the current request and an error ends its spinner', async ({ page, request }) => {
  const id = await send(request)
  await rpc(request, 'HarnessModelChunk', id, '刷新前的内容')
  await expect(page.locator('.ai-response').last()).toContainText('刷新前的内容')
  await page.reload()
  await expect(page.getByTestId('cancel-request')).toBeVisible()
  await expect(page.locator('.ai-response').last()).toHaveText('刷新前的内容')
  await rpc(request, 'HarnessModelChunk', id, '，继续接收')
  await expect(page.locator('.ai-response').last()).toHaveText('刷新前的内容，继续接收')
  await rpc(request, 'HarnessModelFail', id, '合成服务暂时不可用')
  await expect(page.getByTestId('cancel-request')).toBeHidden()
  await expect(page.locator('.inline-error-desc')).toHaveText('合成服务暂时不可用')
  await expect(page.locator('.ai-response').last()).toHaveText('刷新前的内容，继续接收')
})
